# Use source 0190929 for a full release, or 09abc35 with ERP_LEGACY_PLANNING_AMOUNT=70 for a pre-equality partial release; disposable DBs only.
import os
from odoo import api
initial_planning = float(os.environ.get("ERP_LEGACY_PLANNING_AMOUNT", "100"))
assert not env['erp.budget.kpi.release.line']._fields['amount'].store
company = env['res.company'].create({'name': 'Legacy planning seed'})
unit = env['erp.organization.unit'].create({'name': 'Legacy planning OU', 'code': 'LPLAN', 'company_id': company.id})
users = env['res.users'].create([{'name': 'Legacy planning '+name, 'login': 'legacy_planning_'+name, 'company_id': company.id, 'company_ids': [(6, 0, company.ids)], 'group_ids': [(6, 0, env.ref('erp_budget.group_budget_manager').ids)]} for name in ('manager', 'reviewer')])
for user in users:
    env['erp.organization.assignment'].create({'user_id': user.id, 'unit_id': unit.id})
group = env['erp.budget.fund.group'].create({'name': 'Legacy planning group', 'company_id': company.id})
fund = env['erp.budget.fund'].create({'name': 'Legacy planning fund', 'company_id': company.id, 'group_id': group.id})
period = env['erp.budget.period'].create({'name': 'Legacy planning year', 'company_id': company.id, 'date_from': '2027-01-01', 'date_to': '2027-12-31', 'release_policy': 'formal'})
plan = env['account.analytic.plan'].create({'name': 'Legacy planning analytic root'})
analytic = env['account.analytic.account'].create({'name': 'Legacy planning analytic', 'company_id': company.id, 'plan_id': plan.id})
kpi = env['erp.budget.kpi'].create({'name': 'Legacy planning KPI', 'company_id': company.id})
e = api.Environment(env.cr, users[0].id, {'allowed_company_ids': company.ids})
allocation = e['erp.budget.allocation'].create({'name': 'Legacy planning allocation', 'company_id': company.id, 'period_id': period.id, 'line_ids': [(0, 0, {'organization_id': unit.id, 'analytic_id': analytic.id, 'fund_id': fund.id, 'allocated_amount': 100})]})
allocation.action_done()
allocation.plan_id.action_confirm()
allocation.line_ids.control_id.action_open()
control = e['erp.budget.control'].create({'name': 'Legacy planning control', 'company_id': company.id, 'period_id': period.id, 'organization_id': unit.id, 'analytic_id': analytic.id, 'level': 'analytic', 'kpi_id': kpi.id, 'amount': initial_planning})
env['erp.budget.kpi.tier'].create({'company_id': company.id, 'organization_id': unit.id, 'sequence': 10, 'reviewer_id': users[1].id})
release = e['erp.budget.kpi.release'].create({'name': 'Legacy planning released', 'plan_line_id': allocation.plan_id.line_ids.id, 'released_amount': initial_planning, 'line_ids': [(0, 0, {'control_id': control.id})]})
release.action_submit()
release.with_user(users[1]).action_approve()
e['erp.budget.control.service']._commit(control | allocation.line_ids.control_id, 30, '2027-06-01', 'legacy-planning:commitment')
revision = e['erp.budget.allocation.revision'].browse(allocation.action_prepare_allocation_revision()['res_id'])
revision.write({'reason': 'Legacy allocation history'})
revision.action_activate()
env.cr.commit()
print('LEGACY_PLANNING_SEED', release.id, release.line_ids.amount, len(release.review_ids), revision.id, allocation.plan_id.line_ids._consumed())
