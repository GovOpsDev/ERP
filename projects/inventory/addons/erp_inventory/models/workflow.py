class EvaluationResult(models.Model):
    _name = 'erp.inventory.evaluation.result'
    _description = 'Supplier Evaluation Result'
    _check_company_auto = True
    acceptance_id = fields.Many2one('erp.inventory.acceptance', required=True, ondelete='cascade')
    company_id = fields.Many2one(related='acceptance_id.company_id', store=True)
    organization_id = fields.Many2one(related='acceptance_id.organization_id', store=True)
    case_id = fields.Many2one('erp.inventory.evaluation', required=True, check_company=True, ondelete='restrict')
    score_id = fields.Many2one('erp.inventory.evaluation.score', check_company=True, ondelete='restrict')
    note = fields.Char()
    _wa_case_unique = models.Constraint('unique(acceptance_id,case_id)', 'An evaluation case occurs once per acceptance.')

    def _check_result(self):
        self.acceptance_id.check_access('write')
        self.acceptance_id._lock_workflow()
        for result in self:
            wa = result.acceptance_id
            if wa.state == 'cancel' or result.case_id.state_required and wa.state != result.case_id.state_required:
                raise UserError(_('Evaluate at the configured acceptance stage.'))
            if result.score_id and result.score_id.evaluation_id != result.case_id:
                raise ValidationError(_('The score must belong to this evaluation case.'))

    @api.model_create_multi
    def create(self, vals_list):
        with self.env.cr.savepoint():
            records = super().create(vals_list)
            # Empty placeholders for accepted-stage cases are allowed in draft.
            records.filtered('score_id')._check_result()
            records.acceptance_id.check_access('write')
            return records

    def write(self, vals):
        if {'acceptance_id', 'case_id'} & vals.keys():
            raise UserError(_('Evaluation identity is immutable.'))
        with self.env.cr.savepoint():
            self._check_result()
            result = super().write(vals)
            self._check_result()
            return result

    def unlink(self):
        self._check_result()
        if any(wa.state != 'draft' or wa._current_reviews() for wa in self.acceptance_id):
            raise UserError(_('Retain evaluated acceptance results.'))
        return super().unlink()


