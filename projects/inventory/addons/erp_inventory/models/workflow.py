class AcceptanceWorkflow(models.Model):
    _inherit = 'erp.inventory.acceptance'
    paperless = fields.Boolean(default=True)
    committee_ids = fields.One2many('erp.inventory.committee', 'acceptance_id', copy=True)
    evaluation_ids = fields.One2many('erp.inventory.evaluation.result', 'acceptance_id', copy=True)
    review_ids = fields.One2many('erp.inventory.review', 'acceptance_id', readonly=True, copy=False)
    review_round = fields.Integer(readonly=True, copy=False)
    workflow_history = fields.Json(readonly=True, copy=False)
    completeness = fields.Float(compute='_compute_completeness')

    @api.depends('committee_ids.status')
    def _compute_completeness(self):
        for wa in self:
            wa.completeness = 100 * len(wa.committee_ids.filtered('status')) / len(wa.committee_ids) if wa.committee_ids else 0

    def _manager(self):
        self.check_access('write')
        if not self.env.su and not self.env.user.has_group('erp_inventory.group_acceptance_manager'):
            raise AccessError(_('Acceptance management is required.'))

    def _lock_workflow(self):
        self.check_access('read')
        lock_orders(self.purchase_order_id)
        self.invalidate_recordset()

    def _current_reviews(self):
        self.ensure_one()
        return self.review_ids.filtered(lambda r: r.round_number == self.review_round).sorted('sequence')

    def _workflow_write(self, vals):
        # Keep the base immutable state boundary; this method is not RPC callable.
        return super(WorkAcceptance, self).write(vals)

    def _snapshot(self):
        self.ensure_one()
        return {'date': str(fields.Datetime.now()), 'actor_id': self.env.uid, 'state': self.state, 'round': self.review_round,
                'lines': [{'purchase_line_id': l.purchase_line_id.id, 'quantity': l.quantity} for l in self.line_ids],
                'committees': [{'name': c.name, 'employee_id': c.employee_id.id, 'role': c.approve_role, 'status': c.status, 'note': c.note} for c in self.committee_ids],
                'evaluations': [{'case': r.case_id.name, 'score': r.score_id.name, 'value': r.score_id.score, 'note': r.note} for r in self.evaluation_ids],
                'fine': self.fines_late, 'acceptance_date': str(self.acceptance_date), 'manual_acceptance_date': str(self.requested_acceptance_date), 'responsible_id': self.responsible_id.id}

    @api.model_create_multi
    def create(self, vals_list):
        if any(_HISTORY & v.keys() for v in vals_list) or any('default_' + n in self.env.context for n in _HISTORY | {'state', 'acceptance_date', 'name'}):
            raise AccessError(_('Acceptance workflow history is generated by actions.'))
        for vals in vals_list:
            po = self.env['purchase.order'].browse(vals.get('purchase_order_id'))
            if po:
                vals.setdefault('paperless', po.erp_wa_paperless)
                if 'committee_ids' not in vals:
                    source = po.order_line.erp_request_line_id.request_id.committee_ids.filtered(lambda c: c.kind == 'work_acceptance')
                    vals['committee_ids'] = [(0, 0, {'name': c.name, 'employee_id': c.employee_id.id, 'approve_role': c.approve_role, 'note': c.note}) for c in source]
                if 'evaluation_ids' not in vals:
                    vals['evaluation_ids'] = [(0, 0, {'case_id': case.id}) for case in self.env['erp.inventory.evaluation'].search([('company_id', '=', po.company_id.id)])]
        return super().create(vals_list)

    def write(self, vals):
        if _HISTORY & vals.keys():
            raise AccessError(_('Acceptance review history is immutable.'))
        self._lock_workflow()
        if any(wa._current_reviews() for wa in self) and vals.keys() - {'committee_ids', 'evaluation_ids'}:
            raise UserError(_('Reset the acceptance reviews before changing reviewed terms.'))
        return super().write(vals)

    def unlink(self):
        if self.review_ids or any(self.mapped('workflow_history')):
            raise UserError(_('Acceptance workflow history cannot be deleted.'))
        return super().unlink()

    def _check_evaluation(self):
        if not self.env.user.has_group('erp_inventory.group_evaluate_acceptance'):
            return
        for wa in self:
            cases = self.env['erp.inventory.evaluation'].search([('company_id', '=', wa.company_id.id), ('state_required', '=', wa.state)])
            if cases - wa.evaluation_ids.filtered('score_id').case_id:
                raise UserError(_('Complete the required supplier evaluations before accepting work.'))

    def action_request_review(self):
        self._manager()
        with self.env.cr.savepoint():
            self._lock_workflow()
            for wa in self:
                if wa.state != 'draft' or not wa.line_ids:
                    raise UserError(_('Submit a draft acceptance with lines.'))
                if wa._current_reviews() or not wa.paperless:
                    continue
                amount = sum(l.quantity * l.purchase_line_id.price_unit for l in wa.line_ids)
                rate = self.env['erp.budget.control.service']._amount_rate(wa.currency_id, wa.company_id, wa.date_receive, wa.purchase_order_id.erp_budget_manual_rate)
                tiers = self.env['erp.procurement.tier'].search([('company_id', '=', wa.company_id.id), ('kind', '=', 'acceptance'), '|', ('minimum_amount', '=', 0), ('minimum_amount', '<', amount * rate)])
                for tier in tiers:
                    reviewer = tier.reviewer_id
                    if not reviewer.active or not reviewer.has_group('erp_inventory.group_acceptance_manager'):
                        raise ValidationError(_('Acceptance reviewers require active acceptance management capability.'))
                    wa.with_user(reviewer).with_context(allowed_company_ids=wa.company_id.ids).check_access('write')
                if tiers:
                    number = max(wa.review_ids.mapped('round_number'), default=0) + 1
                    wa._workflow_write({'review_round': number})
                    token = _review_internal.set(True)
                    try:
                        self.env['erp.inventory.review'].sudo().create([{'acceptance_id': wa.id, 'sequence': t.sequence, 'reviewer_id': t.reviewer_id.id, 'round_number': number, 'request_snapshot': wa._snapshot()} for t in tiers])
                    finally:
                        _review_internal.reset(token)
        return True

    def action_accept(self):
        with self.env.cr.savepoint():
            self._manager()
            self._lock_workflow()
            self._check_evaluation()
            self.action_request_review()
            if any(any(r.state != 'approved' for r in wa._current_reviews()) for wa in self):
                return True
            result = super().action_accept()
            for wa in self:
                wa._workflow_write({'workflow_history': (wa.workflow_history or []) + [wa._snapshot()]})
            return result

    def action_approve_review(self):
        self.ensure_one()
        self._manager()
        with self.env.cr.savepoint():
            self._lock_workflow()
            reviews = self._current_reviews()
            pending = reviews.filtered(lambda r: r.state == 'pending')[:1]
            if (not pending or pending.reviewer_id != self.env.user) and self.env.user in reviews.filtered(lambda r: r.state == 'approved').reviewer_id:
                return True
            if self.state != 'draft' or not pending or pending.reviewer_id != self.env.user or any(r.state == 'rejected' for r in reviews):
                raise AccessError(_('Only the next acceptance reviewer may approve.'))
            token = _review_internal.set(True)
            try:
                pending.sudo().write({'state': 'approved'})
            finally:
                _review_internal.reset(token)
            if all(r.state == 'approved' for r in reviews):
                return self.action_accept()
        return True

    def action_reject_review(self):
        self.ensure_one()
        self._manager()
        self._lock_workflow()
        pending = self._current_reviews().filtered(lambda r: r.state == 'pending')[:1]
        if self.state != 'draft' or not pending or pending.reviewer_id != self.env.user:
            raise AccessError(_('Only the next acceptance reviewer may reject.'))
        token = _review_internal.set(True)
        try:
            pending.sudo().write({'state': 'rejected'})
        finally:
            _review_internal.reset(token)
        return True

    def _check_unused(self):
        if self.env['stock.picking'].sudo().search_count([('erp_acceptance_id', 'in', self.ids), ('state', '!=', 'cancel')]) or self.env['account.move'].sudo().search_count(['|', ('erp_acceptance_id', 'in', self.ids), ('erp_late_acceptance_id', 'in', self.ids), ('state', '!=', 'cancel')]):
            raise UserError(_('Cancel related receipts, bills and fine charges before cancelling or resetting acceptance.'))

    def action_cancel(self):
        self._manager()
        with self.env.cr.savepoint():
            self._lock_workflow()
            self._check_unused()
            for wa in self:
                if wa.state == 'cancel':
                    continue
                wa._workflow_write({'workflow_history': (wa.workflow_history or []) + [wa._snapshot()], 'state': 'cancel'})
        return True

    def action_reset(self):
        self._manager()
        with self.env.cr.savepoint():
            self._lock_workflow()
            self._check_unused()
            for wa in self:
                wa._workflow_write({'workflow_history': (wa.workflow_history or []) + [wa._snapshot()], 'state': 'draft', 'acceptance_date': False, 'review_round': 0})
                token = _workflow.set(True)
                try:
                    wa.committee_ids.write({'status': False, 'note': False})
                finally:
                    _workflow.reset(token)
        return True


class AcceptanceCommittee(models.Model):
    _name = 'erp.inventory.committee'
    _description = 'Work Acceptance Committee'
    _check_company_auto = True
    acceptance_id = fields.Many2one('erp.inventory.acceptance', required=True, ondelete='cascade')
    company_id = fields.Many2one(related='acceptance_id.company_id', store=True)
    organization_id = fields.Many2one(related='acceptance_id.organization_id', store=True)
    name = fields.Char(required=True)
    employee_id = fields.Many2one('hr.employee', check_company=True, ondelete='restrict')
    approve_role = fields.Selection([('chairman', 'Chairman'), ('committee', 'Committee')], required=True)
    status = fields.Selection([('accept', 'Accepted'), ('not_accept', 'Not accepted'), ('other', 'Other')])
    note = fields.Text()
    _wa_name_unique = models.Constraint('unique(acceptance_id,name)', 'Committee names must be unique within acceptance.')

    def _check_edit(self, vals):
        parents = self.acceptance_id
        parents.check_access('write')
        parents._lock_workflow()
        if not _workflow.get():
            if any(p.state != 'draft' for p in parents) or 'acceptance_id' in vals:
                raise UserError(_('Only draft committee results can change.'))
            if vals.keys() - {'status', 'note'} and any(p._current_reviews() for p in parents):
                raise UserError(_('Committee identities are frozen during review.'))
            if {'status', 'note'} & vals.keys() and not self.env.user.has_group('erp_inventory.group_acceptance_manager'):
                if any(c.employee_id.user_id != self.env.user for c in self):
                    raise AccessError(_('Only the committee member or acceptance manager may record this result.'))
        if vals.get('employee_id'):
            self.env['hr.employee'].browse(vals['employee_id']).check_access('read')

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            parent = self.env['erp.inventory.acceptance'].browse(vals.get('acceptance_id', self.env.context.get('default_acceptance_id')))
            parent.check_access('write')
            parent._lock_workflow()
            if parent.state != 'draft' or parent._current_reviews():
                raise UserError(_('Create committee identities before review.'))
            if vals.get('employee_id'):
                self.env['hr.employee'].browse(vals['employee_id']).check_access('read')
        return super().create(vals_list)

    def write(self, vals):
        self._check_edit(vals)
        return super().write(vals)

    def unlink(self):
        self._check_edit({'name': False})
        return super().unlink()


